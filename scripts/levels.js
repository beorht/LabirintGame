// Converts a map drawing into the level format used by the game
function parseLevelMap(rows) {
    const level = { maze: [], startX: 1, startY: 1, finishX: 1, finishY: 1, traps: [], coins: [] };
    rows.forEach((row, y) => {
        level.maze.push([...row].map((ch, x) => {
            if (ch === 'S') { level.startX = x; level.startY = y; }
            if (ch === 'F') { level.finishX = x; level.finishY = y; }
            if (ch === 'T') level.traps.push(`${x},${y}`);
            if (ch === 'C') level.coins.push(`${x},${y}`);
            return ch === '#' ? 1 : 0;
        }));
    });
    return level;
}

// Level number is 1-based; returns the playable level with its rules
function getLevel(number) {
    const def = LEVELS[number - 1];
    return {
        ...parseLevelMap(def.map),
        number,
        title: def.title,
        goal: def.goal,
        maxLines: def.maxLines || null,
        intro: def.intro || null,
        allowRepeat: number >= REPEAT_LEVEL,
        allowNesting: number >= NESTING_LEVEL
    };
}

